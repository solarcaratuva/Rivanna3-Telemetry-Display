#!/usr/bin/env python3
"""Run CAN-messages' generate_all.py in an isolated build directory.

The submodule contains the DBC sources. A checked-in generated snapshot keeps
the CubeIDE project importable before its first build. Generation runs outside
the submodule and only updates the snapshot when its content changes.
"""

import shutil
import subprocess
import sys
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ThirdParty" / "CAN-messages"
OUTPUT = ROOT / "build" / "can"
PUBLISHED = {
    "c": ROOT / "Common" / "can_structs" / "Src",
    "h": ROOT / "Common" / "can_structs" / "Inc",
}
GENERATORS = ("generate.py", "generate_all.py")
DATABASES = ("BPS.dbc", "MotorController.dbc", "MPPT.dbc", "Rivanna3S.dbc")
GENERATED = ("bps", "motor_controller", "mppt", "rivanna3_s")


def main() -> int:
    missing = [name for name in (*GENERATORS, *DATABASES) if not (SOURCE / name).is_file()]
    if missing:
        print("CAN-messages submodule is missing. Run: git submodule update --init", file=sys.stderr)
        return 1

    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir(parents=True)
    for name in (*GENERATORS, *DATABASES):
        shutil.copy2(SOURCE / name, OUTPUT / name)

    subprocess.run([sys.executable, "generate_all.py"], cwd=OUTPUT, check=True)

    missing_output = [f"{name}.{extension}" for name in GENERATED for extension in ("c", "h")
                      if not (OUTPUT / f"{name}.{extension}").is_file()]
    if missing_output:
        print(f"CAN generation incomplete: {', '.join(missing_output)}", file=sys.stderr)
        return 1

    for directory in PUBLISHED.values():
        directory.mkdir(parents=True, exist_ok=True)
    for name in GENERATED:
        for extension in ("c", "h"):
            filename = f"{name}.{extension}"
            generated = (OUTPUT / filename).read_text()
            generated = re.sub(
                r"(?m)^ \* @brief This (source|header) file was generated by cantools version .*\.$",
                r" * @brief This \1 file was generated from CAN-messages DBCs by cantools.",
                generated,
                count=1,
            )
            published = PUBLISHED[extension] / filename
            if not published.is_file() or published.read_text() != generated:
                published.write_text(generated)

    (OUTPUT / ".generated").touch()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
